import numpy as np, pandas as pd, matplotlib.pyplot as plt
plt.rcParams.update({"text.usetex": True, "font.family": "serif", "font.size": 11})
sp=pd.read_csv('/home/claude/work/data/heft_wide_gauss_testdata_13TeV.csv')
bins=[c for c in sp.columns if c.isdigit()]; F=sp[bins].to_numpy(float)
tot=F.sum(1,keepdims=True); var=np.where(F>0,F*tot/38024.,np.nan)
a4=np.load('/home/claude/ana4/means.npz'); a5=np.load('/home/claude/ana5/ana5.npz')
mhh=255+15*(np.arange(80)+0.5)
C=dict(boot='#C0392B',seeds='#1B6CA8',bnn='#7B4EA3')
fig,ax=plt.subplots(figsize=(6.2,4))
for f,lab,c,ls in [(a4['L1'],'single network','#999999','-'),(a5['L1_boot'],'bootstrap ensemble (mean)',C['boot'],'-'),(a4['mb'],'Bayesian network (posterior mean)',C['bnn'],'--')]:
    ax.plot(mhh,np.nanmean((f-F)**2/var,axis=0),color=c,ls=ls,label=lab)
ax.axhline(1,color='k',ls=':',lw=0.8); ax.set_yscale('log'); ax.set_xlabel(r'$m_{hh}$ [GeV]'); ax.set_ylabel(r'$\langle \chi^2 \rangle$ per bin'); ax.legend(frameon=False,fontsize=9); ax.set_xlim(255,1455)
fig.tight_layout(); fig.savefig('fig_app_accuracy.pdf')
fig,ax=plt.subplots(figsize=(6.2,4))
for f,sd,lab,c,ls in [(a5['L1_boot'],a5['L1_boot_sd'],'bootstrap ensemble',C['boot'],'-'),(a5['L1_seeds'],a5['L1_seeds_sd'],'seeds ensemble',C['seeds'],'--'),(a4['mb'],a4['sb'],'Bayesian network',C['bnn'],':')]:
    z=(F-f)/np.sqrt(var+sd**2); ax.plot(mhh,np.nanstd(z,axis=0),color=c,ls=ls,label=lab)
ax.axhline(1,color='k',ls=':',lw=0.8); ax.set_ylim(0.8,1.8); ax.set_xlabel(r'$m_{hh}$ [GeV]'); ax.set_ylabel(r'standard deviation of the pull $z$'); ax.legend(frameon=False,fontsize=9); ax.set_xlim(255,1455)
fig.tight_layout(); fig.savefig('fig_app_calibration.pdf')
fig,ax=plt.subplots(figsize=(6.2,4))
vt=np.nanmedian(a5['L1_boot_sd']**2/var,axis=0); vo=np.nanmedian(a5['L1_seeds_sd']**2/var,axis=0)
ax.plot(mhh,np.sqrt(vt),color='k',label='bootstrap (training rows and seed)')
ax.plot(mhh,np.sqrt(vo),color=C['seeds'],ls='--',label='seeds (seed only)')
ax.set_yscale('log'); ax.set_xlabel(r'$m_{hh}$ [GeV]'); ax.set_ylabel(r'$[\mathrm{median}\,(s^2/\sigma_k^2)]^{1/2}$'); ax.legend(frameon=False,fontsize=9); ax.set_xlim(255,1455); ax.set_ylim(3e-2,1)
fig.tight_layout(); fig.savefig('fig_app_decomposition.pdf')
d=np.abs(a4['mb']-a5['L1_boot'])/a5['L1_boot_sd']; print('BNN-boot median |d|/s %.2f'%np.nanmedian(d))
mb,mS=a5['L1_boot'],a5['L1_seeds']; print('boot-seeds means median |d|/s %.2f'%np.nanmedian(np.abs(mb-mS)/a5['L1_boot_sd']))
